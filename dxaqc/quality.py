"""Резкость снимка: отказ от оценки, когда измерения на нём недостоверны.

Смаз от движения пациента или расфокус гасят мелкие детали; детектор точек на таком снимке ошибается,
а измерения молча уезжают — на синтетике высота позвонка 58 мм превращалась в 78, а вердикт оставался
«качественное». Поэтому слишком размытый снимок не оцениваем, а просим переснять.

Резкость — отношение энергии второй производной яркости к энергии первой, по каждой оси отдельно;
берём худшую ось, потому что смаз движения гасит частоты только вдоль одного направления. Отношение
не зависит от контраста и от того, насколько ярко снимок экспортирован.

Пороги — 70 % от самого нерезкого из 252 реальных снимков выгрузки (позвоночник 0.052, бедро 0.038).
На реальных снимках ни одного отказа; размытие σ ≥ 1.5 пикселя и смаз на 9–15 пикселей ловятся
на 99–100 % (scripts/blur_check.py). Снимков настолько мутных в выгрузке нет, поэтому на метрики по
типам нарушений проверка не влияет.
"""
import cv2
import numpy as np

SHARPNESS_MIN = {"spine": 0.037, "hip": 0.027}


def sharpness(img):
    """Резкость по худшей из двух осей, см. описание модуля."""
    a = img.astype(np.float32)
    lo, hi = np.percentile(a, [1, 99])
    a = np.clip((a - lo) / max(float(hi - lo), 1e-6), 0, 1).astype(np.float32)
    out = []
    for dx, dy in ((1, 0), (0, 1)):
        g = cv2.Sobel(a, cv2.CV_32F, dx, dy, ksize=3)
        h = cv2.Sobel(a, cv2.CV_32F, 2 * dx, 2 * dy, ksize=3)
        out.append(float((h ** 2).mean() / max(float((g ** 2).mean()), 1e-9)))
    return min(out)


def too_blurred(img, region):
    """(True, резкость, порог), если снимок слишком размыт для надёжных измерений."""
    key = "spine" if region == "spine" else "hip"
    s = sharpness(img)
    return s < SHARPNESS_MIN[key], s, SHARPNESS_MIN[key]
